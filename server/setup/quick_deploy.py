#!/usr/bin/env python3
"""
Quick Deployment Script for QuantTime Servers

Interactive script to deploy R630XL and R810 servers with minimal manual intervention.
"""

import os
import sys
import json
import subprocess
import argparse
from pathlib import Path
from typing import Dict, Any

def print_banner():
    """Print deployment banner"""
    print("=" * 60)
    print("🚀 QuantTime Server Deployment")
    print("=" * 60)
    print("This script will help you deploy R630XL and R810 servers")
    print("for your quant homelab distributed computing infrastructure.")
    print("=" * 60)

def get_user_input(prompt: str, default: str = "") -> str:
    """Get user input with default value"""
    if default:
        user_input = input(f"{prompt} [{default}]: ").strip()
        return user_input if user_input else default
    else:
        return input(f"{prompt}: ").strip()

def validate_ip(ip: str) -> bool:
    """Validate IP address format"""
    try:
        parts = ip.split('.')
        if len(parts) != 4:
            return False
        for part in parts:
            if not 0 <= int(part) <= 255:
                return False
        return True
    except:
        return False

def get_server_config() -> Dict[str, Any]:
    """Get server configuration from user"""
    config = {}
    
    print("\n📋 Server Configuration")
    print("-" * 30)
    
    # R630XL Configuration
    print("\n🖥️ R630XL Server Configuration:")
    config['r630xl'] = {
        'name': get_user_input("Server name", "r630xl"),
        'static_ip': get_user_input("Static IP address", "jupiter"),
        'gateway': get_user_input("Gateway IP", "192.168.2.1"),
        'tailscale_key': get_user_input("Tailscale auth key", ""),
        'username': get_user_input("SSH username", "quanttime"),
        'password': get_user_input("SSH password", "REDACTED_SSH_PASSWORD")
    }
    
    # R810 Configuration
    print("\n🖥️ R810 Server Configuration:")
    config['r810'] = {
        'name': get_user_input("Server name", "r810"),
        'static_ip': get_user_input("Static IP address", "saturn"),
        'gateway': get_user_input("Gateway IP", "192.168.2.1"),
        'tailscale_key': get_user_input("Tailscale auth key", ""),
        'username': get_user_input("SSH username", "quanttime"),
        'password': get_user_input("SSH password", "REDACTED_SSH_PASSWORD")
    }
    
    # GitHub Configuration
    print("\n🔗 GitHub Configuration:")
    config['github'] = {
        'repo_url': get_user_input("GitHub repository URL", "https://github.com/your-repo/QuantTime.git"),
        'token': get_user_input("GitHub token (optional)", "")
    }
    
    return config

def validate_config(config: Dict[str, Any]) -> bool:
    """Validate configuration"""
    print("\n🔍 Validating Configuration...")
    
    # Validate IP addresses
    for server_name, server_config in config.items():
        if server_name in ['r630xl', 'r810']:
            if not validate_ip(server_config['static_ip']):
                print(f"❌ Invalid IP address for {server_name}: {server_config['static_ip']}")
                return False
            
            if not validate_ip(server_config['gateway']):
                print(f"❌ Invalid gateway for {server_name}: {server_config['gateway']}")
                return False
            
            if not server_config['tailscale_key']:
                print(f"❌ Tailscale auth key required for {server_name}")
                return False
    
    print("✅ Configuration validation passed")
    return True

def generate_setup_scripts(config: Dict[str, Any]):
    """Generate setup scripts for each server"""
    print("\n📝 Generating Setup Scripts...")
    
    script_dir = Path("server/setup")
    script_dir.mkdir(parents=True, exist_ok=True)
    
    # Generate R630XL setup script
    r630xl_script = script_dir / "setup_r630xl.sh"
    with open(r630xl_script, 'w') as f:
        f.write(f"""#!/bin/bash
# R630XL Setup Script
# Generated by quick_deploy.py

echo "🚀 Setting up R630XL server..."

# Run the main setup script
sudo ./ubuntu_server_setup.sh \\
  --server-name {config['r630xl']['name']} \\
  --static-ip {config['r630xl']['static_ip']} \\
  --gateway {config['r630xl']['gateway']} \\
  --tailscale-key {config['r630xl']['tailscale_key']} \\
  --github-token {config['github']['token']}

echo "✅ R630XL setup complete!"
""")
    
    # Generate R810 setup script
    r810_script = script_dir / "setup_r810.sh"
    with open(r810_script, 'w') as f:
        f.write(f"""#!/bin/bash
# R810 Setup Script
# Generated by quick_deploy.py

echo "🚀 Setting up R810 server..."

# Run the main setup script
sudo ./ubuntu_server_setup.sh \\
  --server-name {config['r810']['name']} \\
  --static-ip {config['r810']['static_ip']} \\
  --gateway {config['r810']['gateway']} \\
  --tailscale-key {config['r810']['tailscale_key']} \\
  --github-token {config['github']['token']}

echo "✅ R810 setup complete!"
""")
    
    # Make scripts executable
    os.chmod(r630xl_script, 0o755)
    os.chmod(r810_script, 0o755)
    
    print(f"✅ Generated setup scripts:")
    print(f"   - {r630xl_script}")
    print(f"   - {r810_script}")

