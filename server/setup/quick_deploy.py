def main():
    """Main deployment function"""
    parser = argparse.ArgumentParser(description="Quick deployment for QuantTime servers")
    parser.add_argument("--config", help="Path to configuration file")
    parser.add_argument("--generate-only", action="store_true", help="Generate scripts only, don't deploy")
    
    args = parser.parse_args()
    
    print_banner()
    
    # Load or get configuration
    if args.config and Path(args.config).exists():
        with open(args.config, 'r') as f:
            config = json.load(f)
        print(f"📋 Loaded configuration from {args.config}")
    else:
        config = get_server_config()
        
        # Save configuration
        config_path = Path("server/config/deployment_config.json")
        config_path.parent.mkdir(parents=True, exist_ok=True)
        with open(config_path, 'w') as f:
            json.dump(config, f, indent=2)
        print(f"💾 Saved configuration to {config_path}")
    
    # Validate configuration
    if not validate_config(config):
        print("❌ Configuration validation failed")
        sys.exit(1)
    
    # Generate setup scripts
    generate_setup_scripts(config)
    
    # Generate deployment guide
    generate_deployment_guide(config)
    
    if args.generate_only:
        print("\n✅ Script generation complete!")
        print("Run the generated setup scripts on your servers to complete deployment.")
        return
    
    # Ask for deployment confirmation
    print("\n🚀 Ready to deploy servers!")
    print("This will:")
    print("1. Generate setup scripts")
    print("2. Create deployment guide")
    print("3. Provide instructions for manual deployment")
    
    confirm = input("\nContinue with deployment? (y/N): ").strip().lower()
    if confirm != 'y':
        print("Deployment cancelled.")
        return
    
    print("\n✅ Deployment preparation complete!")
    print("\n📋 Next Steps:")
    print("1. Copy the generated setup scripts to your servers")
    print("2. Run the setup scripts on each server")
    print("3. Update the dashboard configuration with actual Tailscale IPs")
    print("4. Launch the dashboard and test connections")
    print("\n📖 See server/docs/DEPLOYMENT_GUIDE_QUICK.md for detailed instructions")

if __name__ == "__main__":
    main()
